        public float bucketFrameTransportMinDelta = 0.00001f;


        [Header("DFSPH Boundary-Aware Stabilization")]
        public bool enableBoundaryAwareDfsph = true;

        [Tooltip("Distance from bucket wall/bottom where boundary compensation starts.")]
        [Min(0.001f)]
        public float boundaryInfluenceDistance = 0.055f;

        [Tooltip("How much artificial boundary density is added near walls. Start low.")]
        [Range(0.0f, 2.0f)]
        public float boundaryDensityContribution = 0.65f;

        [Tooltip("Scales alpha near walls to avoid unstable pressure overreaction.")]
        [Range(0.05f, 1.0f)]
        public float boundaryAlphaScaleNearWall = 0.65f;

        [Tooltip("Adds a velocity push away from the wall when compressed or moving into wall.")]
        public bool enableBoundaryPressurePush = true;

        [Range(0.0f, 2.0f)]
        public float boundaryPressurePushStrength = 0.5f;

        [Min(0.001f)]
        public float maxBoundaryPressureVelocityCorrection = 0.25f;

        [Tooltip("Uses moving bucket wall velocity while computing wall-relative compression.")]
        public bool useMovingWallVelocityForBoundaryPush = true;

        [Tooltip("How strongly density error contributes to wall push.")]
        [Range(0.0f, 5.0f)]
        public float boundaryDensityErrorPushScale = 1.0f;


        [Header("SDF Boundary Solver V2 - Conservative Collision")]
        public bool enableConservativeSdfBoundary = true;

        public bool enableSdfPreSolveCollision = true;

        [Tooltip("Extra distance near wall where incoming normal velocity is removed before neighbor search.")]
        [Min(0.0001f)]
        public float sdfSkinDistance = 0.008f;

        [Tooltip("How strongly inward normal velocity is removed near the wall.")]
        [Range(0.0f, 1.0f)]
        public float sdfNormalVelocityRemoval = 1.0f;

        [Tooltip("Tangential damping near SDF wall. Keep low for paint inside bucket.")]
        [Range(0.0f, 1.0f)]
        public float sdfTangentialFriction = 0.08f;

        [Tooltip("Maximum velocity correction by pre-solve SDF per substep.")]
        [Min(0.0001f)]
        public float maxSdfPreSolveVelocityCorrection = 0.45f;

        [Tooltip("Maximum position correction by SDF projection per substep.")]
        [Min(0.0001f)]
        public float maxSdfPositionCorrectionPerStep = 0.003f;

        [Tooltip("Final SDF projection strength. Lower values prevent wall from acting like a piston.")]
        [Range(0.0f, 1.0f)]
        public float sdfProjectionStrength = 0.25f;

        [Tooltip("Use moving bucket wall velocity when resolving SDF boundary.")]
        public bool sdfUseMovingWallVelocity = true;


        [Header("GPU Boundary Particles")]
        public bool enableGpuBoundaryParticles = true;

        [Tooltip("Maximum boundary particles uploaded to GPU.")]
        [Min(0)]
        public int maxBoundaryParticles = 50000;

        [Tooltip("Maximum boundary particles stored per boundary grid cell.")]
        [Min(4)]
        public int maxBoundaryParticlesPerCell = 128;

        [Tooltip("If true, boundary particles outside the grid are ignored and counted.")]
        public bool discardBoundaryParticlesOutsideGrid = true;

        [Tooltip("Print boundary grid diagnostics every N frames. 0 disables logging.")]
        [Min(0)]
        public int boundaryGridStatsLogEveryNFrames = 60;

        [Tooltip("Scales exported boundary psi. Keep 1 initially.")]
        [Min(0.0f)]
        public float boundaryPsiScale = 1.0f;

        [Tooltip("Fallback boundary radius if BoundarySystem does not provide one.")]
        [Min(0.0001f)]
        public float fallbackBoundaryParticleRadius = 0.012f;


        [Header("DFSPH Boundary Particles - Density / Alpha")]
        public bool enableBoundaryParticleDensity = true;

        [Range(0.0f, 3.0f)]
        public float boundaryDensityStrength = 0.45f;

        [Min(0.0f)]
        public float maxBoundaryDensityContribution = 650.0f;

        public bool enableBoundaryParticleAlpha = true;

        [Range(0.0f, 3.0f)]
        public float boundaryAlphaStrength = 0.65f;

        [Min(0)]
        public int minBoundaryNeighborsForFullSupport = 6;

        [Range(0.0f, 1.0f)]
        public float lowBoundaryNeighborDamping = 0.35f;

        [Tooltip("If true, KComputeDensity writes boundary neighbor count and boundary density contribution for debugging.")]
        public bool writeBoundaryDensityDebug = true;


        [Header("DFSPH Boundary Particles - Pressure Correction")]
        public bool enableBoundaryDivergencePressure = true;

        [Range(0.0f, 3.0f)]
        public float boundaryDivergencePressureStrength = 0.55f;

        public bool enableBoundaryDensityPressure = true;

        [Range(0.0f, 3.0f)]
        public float boundaryDensityPressureStrength = 0.65f;

        [Min(0.0f)]
        public float maxBoundaryDivergenceVelocityCorrection = 0.20f;

        [Min(0.0f)]
        public float maxBoundaryDensityVelocityCorrection = 0.25f;

        [Tooltip("Use boundary particle velocity when computing divergence against moving bucket walls.")]
        public bool useBoundaryVelocityInPressure = true;

        [Tooltip("Optional normal filter. Keep false until normals are verified.")]
        public bool enableBoundaryNormalFiltering = false;

        [Range(-1.0f, 1.0f)]
        public float boundaryNormalMinDot = -0.25f;

        [Tooltip("Debug multiplier. Keep 1.0 initially.")]
        [Range(0.0f, 3.0f)]
        public float boundaryPressureDebugScale = 1.0f;


        [Header("DFSPH Boundary Particles - Collision PreSolve")]
        public bool enableBoundaryParticleCollisionPreSolve = true;

        [Tooltip("Collision distance as multiplier of support radius.")]
        [Range(0.05f, 1.0f)]
        public float boundaryCollisionDistanceFactor = 0.45f;

        [Tooltip("Removes inward velocity relative to boundary normal.")]
        [Range(0.0f, 1.0f)]
        public float boundaryCollisionNormalVelocityRemoval = 1.0f;

        [Tooltip("Tangential damping near boundary particles.")]
        [Range(0.0f, 1.0f)]
        public float boundaryCollisionTangentialFriction = 0.08f;

        [Tooltip("Maximum velocity correction per substep from boundary-particle collision.")]
        [Min(0.0f)]
        public float maxBoundaryCollisionVelocityCorrection = 0.18f;

        [Tooltip("Very small position correction if particle is too close to boundary.")]
        [Min(0.0f)]
        public float maxBoundaryCollisionPositionCorrection = 0.0015f;

        [Tooltip("Use boundary particle velocity for moving bucket collision.")]
        public bool useBoundaryVelocityInCollision = true;

        [Tooltip("Only collide with boundary particles whose normal faces the fluid particle.")]
        public bool enableBoundaryCollisionNormalFilter = true;

        [Range(-1.0f, 1.0f)]
        public float boundaryCollisionNormalMinDot = 0.15f;

        public int GridCellCount =>
            Mathf.Max(1, gridResolution.x) *
            Mathf.Max(1, gridResolution.y) *
            Mathf.Max(1, gridResolution.z);

        private void OnValidate()
        {
            maxParticles = Mathf.Max(128, maxParticles);
            restDensity = Mathf.Max(1.0f, restDensity);
            particleRadius = Mathf.Max(0.0001f, particleRadius);
            supportRadius = Mathf.Max(particleRadius * 2.0f, supportRadius);
            gridCellSize = Mathf.Max(0.001f, gridCellSize);

            gridResolution.x = Mathf.Max(1, gridResolution.x);
            gridResolution.y = Mathf.Max(1, gridResolution.y);
            gridResolution.z = Mathf.Max(1, gridResolution.z);

            if (maxParticlesPerCell < 4)
                maxParticlesPerCell = 4;

            // For the 27-cell neighbor search to be correct,
            // gridCellSize should be at least supportRadius.
            if (gridCellSize < supportRadius)
                gridCellSize = supportRadius;

            if (minDensityClamp < 1.0f)
                minDensityClamp = 1.0f;

            if (maxDensityClamp < minDensityClamp)
                maxDensityClamp = minDensityClamp;

            if (alphaDenominatorEpsilon < 1e-12f)
                alphaDenominatorEpsilon = 1e-12f;

            if (maxAlpha < 0.0001f)
                maxAlpha = 0.0001f;

            if (minNeighborsForFullAlpha < 0)
                minNeighborsForFullAlpha = 0;

            lowNeighborAlphaDamping = Mathf.Clamp01(lowNeighborAlphaDamping);

            if (divergenceErrorScale < 0.0f)
                divergenceErrorScale = 0.0f;

            if (divergenceCorrectionStrength < 0.0f)
                divergenceCorrectionStrength = 0.0f;

            if (maxDivergencePressure < 0.0f)
                maxDivergencePressure = 0.0f;

            if (maxDivergenceVelocityCorrection < 0.01f)
                maxDivergenceVelocityCorrection = 0.01f;

            if (densityErrorScale < 0.0f)
                densityErrorScale = 0.0f;

            if (densityCorrectionStrength < 0.0f)
                densityCorrectionStrength = 0.0f;

            if (maxDensityPressure < 0.0f)
                maxDensityPressure = 0.0f;

            if (maxDensityVelocityCorrection < 0.01f)
                maxDensityVelocityCorrection = 0.01f;


            bucketBoundaryPasses = Mathf.Clamp(bucketBoundaryPasses, 1, 4);

            if (bucketBoundaryPadding < 0.0f)
                bucketBoundaryPadding = 0.0f;

            bucketBoundaryPositionCorrectionStrength =
                Mathf.Clamp01(bucketBoundaryPositionCorrectionStrength);

            bucketBoundaryVelocityCorrectionStrength =
                Mathf.Clamp01(bucketBoundaryVelocityCorrectionStrength);

            bucketBoundaryRestitution =
                Mathf.Clamp01(bucketBoundaryRestitution);

            bucketBoundaryFriction =
                Mathf.Clamp01(bucketBoundaryFriction);


            movingWallVelocityStrength = Mathf.Clamp01(movingWallVelocityStrength);

            if (maxMovingWallVelocity < 0.01f)
                maxMovingWallVelocity = 0.01f;

            if (maxPreSolveWallVelocityCorrection < 0.01f)
                maxPreSolveWallVelocityCorrection = 0.01f;

            if (preSolveWallInfluenceDistance < 0.0f)
                preSolveWallInfluenceDistance = 0.0f;

            preSolveWallVelocityCorrectionStrength =
                Mathf.Clamp01(preSolveWallVelocityCorrectionStrength);

            xsphViscosityStrength = Mathf.Clamp01(xsphViscosityStrength);

            if (maxPaintMaterialVelocityCorrection < 0.001f)
                maxPaintMaterialVelocityCorrection = 0.001f;

            cohesionStrength = Mathf.Clamp(cohesionStrength, 0.0f, 2.0f);
            cohesionDistanceFactor = Mathf.Clamp(cohesionDistanceFactor, 0.05f, 1.0f);
            antiSprayDamping = Mathf.Clamp01(antiSprayDamping);

            if (antiSprayNeighborThreshold < 0)
                antiSprayNeighborThreshold = 0;

            if (wallAdhesionDistance < 0.0f)
                wallAdhesionDistance = 0.0f;

            wallTangentialDamping = Mathf.Clamp01(wallTangentialDamping);
            wallNormalDamping = Mathf.Clamp01(wallNormalDamping);
            wallAdhesionAttraction = Mathf.Clamp01(wallAdhesionAttraction);

            bucketFramePositionTransportStrength = Mathf.Clamp01(bucketFramePositionTransportStrength);

            bucketFrameVelocityTransportStrength = Mathf.Clamp01(bucketFrameVelocityTransportStrength);

            if (maxBucketFrameTransportVelocity < 0.01f)
                maxBucketFrameTransportVelocity = 0.01f;

            if (bucketFrameTransportMinDelta < 0.0f)
                bucketFrameTransportMinDelta = 0.0f;


            if (boundaryInfluenceDistance < 0.001f)
                boundaryInfluenceDistance = 0.001f;

            boundaryDensityContribution =
                Mathf.Clamp(boundaryDensityContribution, 0.0f, 2.0f);

            boundaryAlphaScaleNearWall =
                Mathf.Clamp(boundaryAlphaScaleNearWall, 0.05f, 1.0f);

            boundaryPressurePushStrength =
                Mathf.Clamp(boundaryPressurePushStrength, 0.0f, 2.0f);

            if (maxBoundaryPressureVelocityCorrection < 0.001f)
                maxBoundaryPressureVelocityCorrection = 0.001f;

            boundaryDensityErrorPushScale =
                Mathf.Clamp(boundaryDensityErrorPushScale, 0.0f, 5.0f);

            if (sdfSkinDistance < 0.0001f)
                sdfSkinDistance = 0.0001f;

            sdfNormalVelocityRemoval =
                Mathf.Clamp01(sdfNormalVelocityRemoval);

            sdfTangentialFriction =
                Mathf.Clamp01(sdfTangentialFriction);

            if (maxSdfPreSolveVelocityCorrection < 0.0001f)
                maxSdfPreSolveVelocityCorrection = 0.0001f;

            if (maxSdfPositionCorrectionPerStep < 0.0001f)
                maxSdfPositionCorrectionPerStep = 0.0001f;

            sdfProjectionStrength = Mathf.Clamp01(sdfProjectionStrength);

            if (maxBoundaryParticles < 0)
                maxBoundaryParticles = 0;

            if (maxBoundaryParticlesPerCell < 4)
                maxBoundaryParticlesPerCell = 4;

            if (boundaryGridStatsLogEveryNFrames < 0)
                boundaryGridStatsLogEveryNFrames = 0;

            if (boundaryPsiScale < 0.0f)
                boundaryPsiScale = 0.0f;

            if (fallbackBoundaryParticleRadius < 0.0001f)
                fallbackBoundaryParticleRadius = 0.0001f;

            boundaryDensityStrength = Mathf.Clamp(boundaryDensityStrength, 0.0f, 3.0f);

            if (maxBoundaryDensityContribution < 0.0f)
                maxBoundaryDensityContribution = 0.0f;

            boundaryAlphaStrength =
                Mathf.Clamp(boundaryAlphaStrength, 0.0f, 3.0f);

            if (minBoundaryNeighborsForFullSupport < 0)
                minBoundaryNeighborsForFullSupport = 0;

            lowBoundaryNeighborDamping =
                Mathf.Clamp01(lowBoundaryNeighborDamping);

            boundaryDivergencePressureStrength = Mathf.Clamp(boundaryDivergencePressureStrength, 0.0f, 3.0f);

            boundaryDensityPressureStrength =
                Mathf.Clamp(boundaryDensityPressureStrength, 0.0f, 3.0f);

            if (maxBoundaryDivergenceVelocityCorrection < 0.0f)
                maxBoundaryDivergenceVelocityCorrection = 0.0f;

            if (maxBoundaryDensityVelocityCorrection < 0.0f)
                maxBoundaryDensityVelocityCorrection = 0.0f;

            boundaryNormalMinDot =
                Mathf.Clamp(boundaryNormalMinDot, -1.0f, 1.0f);

            boundaryPressureDebugScale =
                Mathf.Clamp(boundaryPressureDebugScale, 0.0f, 3.0f);

            boundaryCollisionDistanceFactor = Mathf.Clamp(boundaryCollisionDistanceFactor, 0.05f, 1.0f);

            boundaryCollisionNormalVelocityRemoval = Mathf.Clamp01(boundaryCollisionNormalVelocityRemoval);

            boundaryCollisionTangentialFriction = Mathf.Clamp01(boundaryCollisionTangentialFriction);

            if (maxBoundaryCollisionVelocityCorrection < 0.0f)
                maxBoundaryCollisionVelocityCorrection = 0.0f;

            if (maxBoundaryCollisionPositionCorrection < 0.0f)
                maxBoundaryCollisionPositionCorrection = 0.0f;

            boundaryCollisionNormalMinDot = Mathf.Clamp(boundaryCollisionNormalMinDot, -1.0f, 1.0f);
        }
    }
}