        [Range(0.0f, 1.0f)]
        public float wallNormalDamping = 0.25f;

        [Tooltip("Small attraction toward wall for wet paint behavior. Keep low.")]
        [Range(0.0f, 1.0f)]
        public float wallAdhesionAttraction = 0.05f;

        [Header("DFSPH Bucket Frame Transport / Anti-Collapse")]
        public bool enableBucketFrameTransport = true;

        [Tooltip("Moves particles with the bucket transform delta before pressure solve. Useful for kinematic/parent-driven bucket motion.")]
