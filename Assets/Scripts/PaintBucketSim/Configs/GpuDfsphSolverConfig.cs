        public float preSolveWallVelocityCorrectionStrength = 0.4f;


        [Header("DFSPH Paint Material - Viscosity / Cohesion")]
        public bool enablePaintMaterialModel = true;

        [Tooltip("XSPH viscosity strength. Higher values make paint move more like a thick fluid.")]
        [Range(0.0f, 1.0f)]
        public float xsphViscosityStrength = 0.12f;

        [Tooltip("Maximum velocity change from viscosity/cohesion per pass.")]
        [Min(0.001f)]
        public float maxPaintMaterialVelocityCorrection = 0.15f;

        [Tooltip("Cohesion strength between nearby particles. Helps paint stay together.")]
        [Range(0.0f, 2.0f)]
        public float cohesionStrength = 0.25f;

        [Tooltip("Distance factor below which cohesion becomes stronger. Relative to support radius.")]
        [Range(0.05f, 1.0f)]
        public float cohesionDistanceFactor = 0.65f;

        [Tooltip("Damps isolated fast particles to reduce spray-like behavior.")]
        [Range(0.0f, 1.0f)]
        public float antiSprayDamping = 0.15f;

        [Tooltip("Neighbor count below which anti-spray damping starts.")]
        [Min(0)]
        public int antiSprayNeighborThreshold = 6;

        [Header("DFSPH Paint Material - Wall Adhesion")]
        public bool enableWallAdhesionDamping = true;

        [Tooltip("Distance from bucket wall where adhesion damping is applied.")]
        [Min(0.0f)]
        public float wallAdhesionDistance = 0.025f;

        [Tooltip("Tangential velocity damping near wall.")]
        [Range(0.0f, 1.0f)]
        public float wallTangentialDamping = 0.35f;

